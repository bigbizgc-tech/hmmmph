// Copies the static site (docs/, built by the repo's `node build.mjs`) into public/ and writes
// src/generated/site.mjs: the file list, the redirect map, and the home and 404 pages the server
// answers with. Run by release.mjs and scripts/dev.mjs; `node scripts/sync-site.mjs` on its own.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const DOCS = resolve(ROOT, "../../docs");
const PUBLIC = join(ROOT, "public");
const GENERATED = join(ROOT, "src/generated/site.mjs");

// Files for other hosts (GitHub Pages, Netlify/Cloudflare redirects): routing lives in
// src/redirects.json here.
const SKIP = new Set([".nojekyll", "_redirects", "_headers", ".DS_Store"]);

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(join(dir, d.name)) : [join(dir, d.name)],
  );
}

export function syncSite() {
  if (!existsSync(join(DOCS, "index.html")) || !existsSync(join(DOCS, "404.html"))) {
    throw new Error(`${DOCS} has no index.html or 404.html: run \`node build.mjs\` at the repo root first`);
  }
  rmSync(PUBLIC, { recursive: true, force: true });
  cpSync(DOCS, PUBLIC, { recursive: true, filter: (src) => !SKIP.has(src.split(sep).pop()) });

  const files = walk(PUBLIC).map((f) => `/${relative(PUBLIC, f).split(sep).join("/")}`).sort();
  const known = new Set(files);
  const redirects = JSON.parse(readFileSync(join(ROOT, "src/redirects.json"), "utf8"));
  const map = { exact: redirects.exact ?? {}, prefix: redirects.prefix ?? {} };
  const bad = Object.entries({ ...map.exact, ...map.prefix }).filter(
    ([from, to]) =>
      from !== from.toLowerCase() || from.endsWith("/") || !(to === "/" || known.has(to.split(/[?#]/)[0])),
  );
  if (bad.length) {
    throw new Error(
      `src/redirects.json: keys must be lower-case without a trailing slash, targets files in docs/:\n` +
        bad.map(([from, to]) => `  ${from} -> ${to}`).join("\n"),
    );
  }

  const read = (f) => readFileSync(join(PUBLIC, f), "utf8");
  mkdirSync(dirname(GENERATED), { recursive: true });
  writeFileSync(
    GENERATED,
    `// Generated by scripts/sync-site.mjs from docs/ and src/redirects.json. Do not edit.\n` +
      `export const files = ${JSON.stringify(files)};\n` +
      `export const redirects = ${JSON.stringify(map)};\n` +
      `export const indexHtml = ${JSON.stringify(read("index.html"))};\n` +
      `export const notFoundHtml = ${JSON.stringify(read("404.html"))};\n`,
  );
  return { files: files.length, from: DOCS };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = syncSite();
  console.log(`synced ${r.files} files from ${r.from} into public/`);
}
